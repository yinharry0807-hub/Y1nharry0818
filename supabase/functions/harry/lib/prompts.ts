export function profileUpdatePrompt(text: string): string {
  return `你是 Harry 的档案助理。用户刚描述了一段自己的近况，请提炼成结构化摘要。
要求：
- 客观、不修饰、不补全用户没说的事实；
- 如果原文包含数字、金额、时间、目标、公司名等关键信息，必须原样保留；
- 用一句话概括核心变化，不超过 80 字；
- tags 从以下范围中最多选 3 个：工作、财务、目标、心态、健康、学习、家庭、社交、其他。

输出 JSON 格式：{"summary": "一句话摘要", "tags": ["工作"]}

用户的近况原文：
${text}`
}

export function knowledgeClassifyPrompt(content: string): string {
  return `你是 Harry 顾问的知识管理员。用户粘贴了一段知识内容，请判断它对他是否有用。

用户背景（简要）：22 岁，服装供应链跟单（跨境快时尚，约 1 年经验），计划 2027 年跳槽广深甲方供应链/采购/商品岗，月薪 4500 元有储蓄目标，在学英语、AI 工具和健身。

分类标准：
- "当前阶段有用"：能直接指导他未来 1-2 年的求职、工作方法、储蓄理财、健身、英语、AI 工具使用、职场沟通。
- "未来有用"：方向正确，但现阶段用不上（如创业、股权投资、管理方法论、买房等），封存备用。
- "有误导性"：贩卖焦虑、速成暴富、成功学鸡汤、割韭菜、有害健康、与事实明显不符的毒药内容。

输出 JSON 格式：
{"category": "当前阶段有用|未来有用|有误导性", "title": "不超过20字的标题", "summary": "不超过150字，说清核心要点，以及对他为什么有用/为什么有害", "reason": "一句判断依据"}

待判断的内容：
${content}`
}

export function resumeGeneratePrompt(targetRole: string, raw: string, baseText: string): string {
  const roleHint: Record<string, string> = {
    supply:
      "目标岗位：甲方品牌/跨境电商的供应链、采购岗。重点突出：全流程跟单、供应商沟通、成本与交期控制、跨部门协调、风险管理。",
    merchandise:
      "目标岗位：跨境电商商品岗（商品企划/买手/商品运营）。重点突出：对跨境快时尚市场需求的理解、品类与款式跟进、销售数据敏感度、商品周转意识。",
    general:
      "目标岗位：通用版本（供应链/采购/商品方向均可投递）。平衡突出：全流程跟单能力、沟通协调、执行力、英语与 AI 工具学习意愿。"
  }
  const hint = roleHint[targetRole] || ""

  return `你是资深简历顾问，为一位 22 岁、2026 年应届毕业生润色简历。你只做两件事：措辞优化、重点突出；绝对禁止编造不存在的核心经历、公司、项目、数据、职级或成果。

${hint}

已知真实背景（客观事实，可以引用，但不得夸大或伪造数字）：
${(baseText || "").slice(0, 3000)}

用户提供的原始经历素材（必须基于此润色，不得虚构素材之外的核心经历）：
${raw || "（未提供，仅使用已知背景）"}

输出 JSON 格式：
{
  "summary": "个人总结（100-150字，突出跨境服装供应链全流程跟单与跳槽方向）",
  "experience": [
    {"company": "公司名", "position": "岗位", "period": "时间", "bullets": ["以动词开头的成果型描述，3-5条"]}
  ],
  "skills": ["3-6个技能关键词"],
  "keywords": ["3-8个简历筛选关键词，贴合目标岗位"]
}

约束：bullets 每条不超过 40 字；不得出现"精通""负责所有""主导公司级"等无法支撑的表述；可以写"熟悉""参与""跟进"等与真实工作相符的措辞。`
}

export function newsGeneratePrompt(mode: string): string {
  const userContext = `用户背景：22 岁，广东人，在珠海做跨境快时尚服装供应链跟单（服务知名跨境快时尚品牌），约 1 年经验；2027 年春节后计划跳槽广州/深圳的甲方供应链、采购、商品岗；月薪约 4500 元，有 2027 春节存 1.5 万的目标；在学英语口语、AI 工具、健身。`
  if (mode === "daily") {
    return `${userContext}

请基于你掌握的最新知识，为这位用户推荐"今日一条"最有价值的内容。要求：
- 只选一条，宁缺毋滥；
- 必须与他当前阶段直接相关：跨境供应链/服装行业动态、求职机会、技能学习（英语/AI/Excel）、认知成长中选最紧迫的一类；
- 不得推荐鸡汤、速成暴富、割韭菜内容；
- why_useful 必须具体到他身上，说清"为什么对他有用、他怎么用"，拒绝泛泛而谈。

输出 JSON 格式：
{"items": [{"category": "行业动态|求职机会|技能学习|认知成长", "title": "标题", "summary": "80-150字的内容要点", "why_useful": "为什么对这位用户有用，50-100字"}]}`
  }
  return `${userContext}

请基于你掌握的最新知识，为这位用户生成"每周一辑"资讯合集，共 6 条：
- 行业动态 1-2 条：跨境服装/快时尚供应链相关；
- 求职机会 1-2 条：广深供应链/采购/商品岗相关（含招聘趋势、岗位要求变化、准备建议）；
- 技能学习 1-2 条：英语口语、AI 工具（如 Excel 自动化/提示词）、供应链术语；
- 认知成长 1 条：与执行力、焦虑、长期主义相关，且对他有真实可操作价值。

要求：不得推荐鸡汤、速成暴富、割韭菜内容；每条 why_useful 必须具体到他身上。

输出 JSON 格式：
{"items": [{"category": "行业动态|求职机会|技能学习|认知成长", "title": "标题", "summary": "80-150字的内容要点", "why_useful": "为什么对这位用户有用，50-100字"}]}`
}
